#!/usr/bin/env python3
"""Generate the 12x12 1-bit HUD icon atlas from CC0 Kenney sources.

Sources:
  assets/icons/board/*.png    Kenney Board Game Icons (CC0)
  assets/icons/game/gear.png  Kenney Game Icons (CC0)

Run from the repo root:
  python tools/gen_icons.py
"""
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
BOARD = ROOT / "assets" / "icons" / "board"
GAME = ROOT / "assets" / "icons" / "game"
OUT = ROOT / "src" / "engine" / "icons.zig"
SIZE = 12
THRESHOLD = 70

ICONS = [
    ("bag", BOARD / "pouch.png"),
    ("hero", BOARD / "crown_a.png"),
    ("coin", BOARD / "dollar.png"),
    ("sword", BOARD / "sword.png"),
    ("shield", BOARD / "shield.png"),
    ("potion", BOARD / "flask_full.png"),
    ("time", BOARD / "hourglass.png"),
    ("fire", BOARD / "campfire.png"),
    ("skull", BOARD / "skull.png"),
    ("heart", BOARD / "suit_hearts.png"),
    ("gear", GAME / "gear.png"),
]


def rows_for(path: Path) -> list[int]:
    image = Image.open(path).convert("RGBA").resize((SIZE, SIZE), Image.LANCZOS)
    rows: list[int] = []
    for y in range(SIZE):
        bits = 0
        for x in range(SIZE):
            if image.getpixel((x, y))[3] > THRESHOLD:
                bits |= 1 << (SIZE - 1 - x)
        rows.append(bits)
    return rows


def main() -> None:
    lines = [
        "//! 12x12 1-bit HUD icons derived from Kenney Board Game Icons / Game Icons (CC0).",
        "//! Generated by tools/gen_icons.py; edit that script, not this file.",
        "",
        "pub const size: u8 = 12;",
        "",
        "pub const Icon = enum(u8) { " + ", ".join(key for key, _ in ICONS) + " };",
        "",
        "pub fn rows(icon: Icon) [12]u16 {",
        "    return switch (icon) {",
    ]
    for key, path in ICONS:
        rows = rows_for(path)
        lines.append("        .%s => .{ %s }," % (key, ", ".join("0x%03x" % row for row in rows)))
    lines += [
        "    };",
        "}",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(ICONS)} icons)")


if __name__ == "__main__":
    main()
