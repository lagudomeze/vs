#!/usr/bin/env python3
"""Generate src/core/cjk_font.zig from the Ark Pixel 12px monospaced BDF.

The font is SIL OFL 1.1; only the glyph bitmaps for characters used by the
game are embedded. The BDF itself is not committed (download it from
https://github.com/TakWolf/ark-pixel-font).

Usage:
  python tools/gen_cjk_font.py [--bdf PATH] [--out PATH]
"""
from __future__ import annotations

import argparse
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
DEFAULT_BDF = ROOT / ".tmp-font" / "bdf" / "ark-pixel-12px-monospaced-zh_hans.bdf"
OUT = ROOT / "src" / "core" / "cjk_font.zig"
LICENSE_OUT = ROOT / "assets" / "fonts" / "OFL.txt"

# Characters that are not necessarily in source yet (enemy/skill names, etc.).
EXTRA = (
    "以太堡真像素渲染操作移动转动轮缩放切换空格技能重开调试退出"
    "队伍狂战士元素法师时空级倒下复活状态波次余敌视角距离帧率三角消耗"
    "第来袭胜利全灭按击杀骷髅兵幽魂石魔像深渊守卫首领目标锁定暴击减速"
    "准备波重击火球光箭生命护盾攻击防御治疗恢复召唤冷却范围近战远程"
)


def parse_bdf(path: pathlib.Path):
    ascent = 10
    width = 12
    height = 12
    glyphs = {}
    cur = None
    with path.open(encoding="utf-8", errors="ignore") as f:
        for line in f:
            line = line.rstrip("\n")
            if line.startswith("FONT_ASCENT "):
                ascent = int(line.split()[1])
            elif line.startswith("FONTBOUNDINGBOX "):
                p = line.split()
                width, height = int(p[1]), int(p[2])
            elif line.startswith("STARTCHAR"):
                cur = {"rows": [], "bbx": None, "cp": None}
            elif cur is not None:
                if line.startswith("ENCODING "):
                    cur["cp"] = int(line.split()[1])
                elif line.startswith("BBX "):
                    p = line.split()
                    cur["bbx"] = tuple(int(x) for x in p[1:5])
                elif line.startswith("ENDCHAR"):
                    if cur["cp"] is not None and cur["bbx"] and cur["rows"]:
                        glyphs[cur["cp"]] = cur
                    cur = None
                elif cur["bbx"] and line and all(ch in "0123456789abcdefABCDEF" for ch in line):
                    cur["rows"].append(line)
    return ascent, width, height, glyphs


def cell_bitmap(glyph, ascent: int, cell_w: int, cell_h: int):
    w, h, xo, yo = glyph["bbx"]
    rows = [0] * cell_h
    if not glyph["rows"]:
        return rows
    bits_per_row = len(glyph["rows"][0]) * 4
    for r, hexrow in enumerate(glyph["rows"]):
        cy = ascent - (yo + h) + r
        if cy < 0 or cy >= cell_h:
            continue
        value = int(hexrow, 16)
        out = 0
        for c in range(w):
            if (value >> (bits_per_row - 1 - c)) & 1:
                cx = xo + c
                if 0 <= cx < cell_w:
                    out |= 1 << (cell_w - 1 - cx)
        rows[cy] = out
    return rows


def collect_codepoints() -> set[int]:
    cps = {ord(ch) for ch in EXTRA if ord(ch) > 0x7F}
    for path in sorted((ROOT / "src").rglob("*.zig")):
        text = path.read_text(encoding="utf-8", errors="ignore")
        cps.update(ord(ch) for ch in text if ord(ch) > 0x7F)
    return cps


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--bdf", type=pathlib.Path, default=DEFAULT_BDF)
    ap.add_argument("--out", type=pathlib.Path, default=OUT)
    args = ap.parse_args()
    if not args.bdf.exists():
        print(f"BDF not found: {args.bdf}", file=sys.stderr)
        print("Download ark-pixel-font-12px-monospaced-bdf and extract it to .tmp-font/bdf/", file=sys.stderr)
        return 1

    ascent, cell_w, cell_h, all_glyphs = parse_bdf(args.bdf)
    wanted = collect_codepoints()
    packed = []
    missing = []
    for cp in sorted(wanted):
        glyph = all_glyphs.get(cp)
        if glyph is None:
            missing.append(cp)
            continue
        packed.append((cp, cell_bitmap(glyph, ascent, cell_w, cell_h)))

    args.out.parent.mkdir(parents=True, exist_ok=True)
    with args.out.open("w", encoding="utf-8", newline="\n") as f:
        f.write("//! Generated by tools/gen_cjk_font.py - do not edit by hand.\n")
        f.write("//! Glyphs are from Ark Pixel Font 12px (https://github.com/TakWolf/ark-pixel-font),\n")
        f.write("//! SIL Open Font License 1.1. See assets/fonts/OFL.txt.\n")
        f.write(f"pub const width: u32 = {cell_w};\n")
        f.write(f"pub const height: u32 = {cell_h};\n")
        f.write("pub const advance: u32 = 13;\n")
        f.write(f"pub const ascent: u32 = {ascent};\n\n")
        f.write("pub const Glyph = struct { cp: u21, rows: [" + str(cell_h) + "]u16 };\n\n")
        f.write("const glyphs = [_]Glyph{\n")
        for cp, rows in packed:
            row_text = ", ".join(f"0x{r:03X}" for r in rows)
            f.write(f"    .{{ .cp = 0x{cp:X}, .rows = .{{ {row_text} }} }},\n")
        f.write("};\n\n")
        f.write("pub fn find(cp: u21) ?*const Glyph {\n")
        f.write("    var lo: usize = 0;\n")
        f.write("    var hi: usize = glyphs.len;\n")
        f.write("    while (lo < hi) {\n")
        f.write("        const mid = lo + (hi - lo) / 2;\n")
        f.write("        if (glyphs[mid].cp < cp) lo = mid + 1 else hi = mid;\n")
        f.write("    }\n")
        f.write("    if (lo < glyphs.len and glyphs[lo].cp == cp) return &glyphs[lo];\n")
        f.write("    return null;\n")
        f.write("}\n")

    license_src = args.bdf.parent / "OFL.txt"
    if license_src.exists():
        LICENSE_OUT.parent.mkdir(parents=True, exist_ok=True)
        LICENSE_OUT.write_bytes(license_src.read_bytes())

    print(f"wrote {len(packed)} glyphs to {args.out}")
    if missing:
        print("missing codepoints:", ", ".join(f"U+{cp:04X}" for cp in missing))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
