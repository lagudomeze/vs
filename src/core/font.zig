const fallback = [7]u8{ 0b11111, 0b10001, 0b10001, 0b10001, 0b10001, 0b10001, 0b11111 };

pub fn glyph(c: u8) [7]u8 {
    var ch = c;
    if (ch >= 'a' and ch <= 'z') ch -= 32;
    for (glyphs) |g| {
        if (g.ch == ch) return g.rows;
    }
    return fallback;
}

pub fn textWidth(text: []const u8, scale: u32) u32 {
    if (text.len == 0) return 0;
    return (text.len * advance - 1) * scale;
}

